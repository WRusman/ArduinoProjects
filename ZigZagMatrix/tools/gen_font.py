def encode(glyphs, w, h, first=32, last=126, fold_case=False):
    out = []
    for code in range(first, last + 1):
        ch = chr(code)
        src = ch.upper() if (fold_case and ch.isalpha()) else ch
        art = glyphs.get(src)
        if art is None:
            art = glyphs[' ']
        rows = art.split('|')
        assert len(rows) == h, f"{ch!r}: {len(rows)} rows, want {h}"
        for r in rows:
            assert len(r) == w, f"{ch!r}: row {r!r} width {len(r)}, want {w}"
        cols = []
        for x in range(w):
            b = 0
            for y in range(h):
                if rows[y][x] == '#':
                    b |= (1 << y)
            cols.append(b)
        out.append((ch, cols))
    return out


def emit(name, table, w, h, first, last):
    lines = [f"const uint8_t {name}[] PROGMEM = {{"]
    for ch, cols in table:
        body = ", ".join(f"0x{c:02X}" for c in cols)
        label = ch if ch.isprintable() and ch not in "\\'" else repr(ch)[1:-1]
        lines.append(f"  {body},   // '{label}'")
    lines.append("};")
    return "\n".join(lines)


def preview(table, w, h, chars):
    for ch in chars:
        cols = dict(table)[ch]
        print(f"[{ch}]")
        for y in range(h):
            print("".join('#' if (cols[x] >> y) & 1 else '.' for x in range(w)))
        print()


